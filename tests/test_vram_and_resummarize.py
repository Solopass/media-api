client = TestClient(app)

def test_gpu_service_evaluation():
    fake_vram = {
        "adapter": "AMD Radeon RX 9070 XT",
        "total_vram_gb": 15.9,
        "used_vram_gb": 4.0,
        "free_vram_gb": 11.9,
        "other_apps_vram_gb": 4.0,
        "room_for_model_gb": 11.9,
        "loaded_models": []
    }

    # sol-vision (~7.5 GB) should fit easily in 11.9 GB
    fit_vision = GpuService.evaluate_model_fit("sol-vision:latest", None, fake_vram)
    assert fit_vision["verdict"] == "fits"
    assert "Fits easily" in fit_vision["badge"]

    # sol-fast (~12.4 GB) with 11.9 GB room should be tight
    fit_fast = GpuService.evaluate_model_fit("sol-fast:latest", None, fake_vram)
    assert fit_fast["verdict"] == "tight"
    assert "Tight" in fit_fast["badge"]

    # sol-specialist (~18.5 GB) with 11.9 GB room should exceed VRAM
    fit_spec = GpuService.evaluate_model_fit("sol-specialist:latest", None, fake_vram)
    assert fit_spec["verdict"] == "wont_fit"
    assert "Exceeds VRAM" in fit_spec["badge"]

def test_models_api_endpoint():
    res = client.get("/api/v1/models")
    assert res.status_code == 200
    data = res.json()
    assert "models" in data
    assert "model_details" in data
    assert "default" in data
    assert "gpu" in data
    assert data["gpu"]["total_vram_gb"] > 0

    # Ensure details list contains expected fields
    if data["model_details"]:
        first = data["model_details"][0]
        assert "vram_needed_gb" in first
        assert "verdict" in first
        assert "badge" in first

def test_update_note_summary_method(tmp_path):
    note_file = tmp_path / "test_note.md"
    note_file.write_text("""---
title: "Test Note"
---

# 🎙️ Test Note

> [!abstract] **Executive Briefing**
> *(Automatic LLM summary unavailable: timed out)*

---

## 📋 Metadata
- Source: test
""", encoding="utf-8")

    success = ObsidianService.update_note_summary(
        note_path=note_file,
        new_summary="This is a fresh and high quality AI summary generated by Ollama.",
        summary_preset="executive"
    )

    assert success is True
    updated = note_file.read_text(encoding="utf-8")
    assert "This is a fresh and high quality AI summary" in updated
    assert "timed out" not in updated
    assert "> [!abstract] **Executive Briefing**" in updated
